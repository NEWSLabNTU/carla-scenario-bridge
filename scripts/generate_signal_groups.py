#!/usr/bin/env python3
"""Write CARLA's traffic light groups for a town: `<map dir>/carla/signal_groups.yaml`.

CARLA cycles the lights of a junction as one group, in turn: each light green, then amber,
while every other light of the group is red. A simulator with no light controller of its own
(aib's stand-alone runner on Isaac) runs the same cycle from this file, so the ego meets what
it would meet on CARLA. Lights are named by OpenDRIVE id, as in the signal table
(`carla/traffic_lights.yaml`), which says which regulatory elements each one is. The times
are not in the file: swb freezes CARLA's cycle (every light's green and yellow time set to
99999 s), so what a server reports depends on who drove it last; the runner takes CARLA's
defaults, 10 s green and 3 s amber, as flags.

    scripts/generate_signal_groups.py Town01 [--map data/carla-autoware-bridge/Town01]
        [--port 2000]

Needs CARLA holding the town with something ticking it (swb during a scenario, or a private
server): this script never ticks, it waits for a frame, since a client that has not seen one
sees no actors. It reads the lights and changes nothing.

The file:

    town: Town01
    groups:                 # one per CARLA light group (a junction)
    - lights: ['375', '377', '376']   # OpenDRIVE ids, in the order the group turns green
"""
import argparse
import sys
from pathlib import Path

try:
    import carla
except ImportError:
    sys.exit("carla PythonAPI not importable")
try:
    import yaml
except ImportError:
    sys.exit("PyYAML not importable (python3-yaml)")

HEADER = ("# Generated by scripts/generate_signal_groups.py from CARLA's light groups; read by\n"
          "# aib's stand-alone runner (--signals). Do not edit: regenerate.\n")


def groups_of(lights):
    """CARLA's groups, each once: `[[light, ...]]` in the order CARLA lists a group's lights.

    `lights`: objects with `id` and `get_group_traffic_lights()` (carla.TrafficLight)."""
    seen, groups = set(), []
    for tl in sorted(lights, key=lambda t: t.id):
        if tl.id in seen:
            continue
        group = list(tl.get_group_traffic_lights()) or [tl]
        seen.update(g.id for g in group)
        groups.append(group)
    return groups


def table(town, groups):
    return {"town": town, "groups": [
        {"lights": [str(t.get_opendrive_id()) for t in g]} for g in groups]}


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("town")
    ap.add_argument("--map", help="map dir (default data/carla-autoware-bridge/<town>)")
    ap.add_argument("--host", default="localhost")
    ap.add_argument("--port", type=int, default=2000)
    a = ap.parse_args()
    mdir = Path(a.map or f"data/carla-autoware-bridge/{a.town}")

    client = carla.Client(a.host, a.port)
    client.set_timeout(30.0)
    world = client.get_world()
    loaded = world.get_map().name.rsplit("/", 1)[-1]
    if loaded != a.town:
        sys.exit(f"CARLA holds {loaded}, not {a.town}")
    try:
        world.wait_for_tick(60.0)
    except RuntimeError:
        sys.exit("no frame within 60 s: run this while something ticks the world")

    lights = list(world.get_actors().filter("traffic.traffic_light*"))
    if not lights:
        sys.exit(f"{a.town} has no traffic lights")
    out = table(a.town, groups_of(lights))
    path = mdir / "carla" / "signal_groups.yaml"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(HEADER + yaml.safe_dump(out, sort_keys=False, default_flow_style=None))
    sizes = sorted(len(g["lights"]) for g in out["groups"])
    print(f"{path}: {len(lights)} light(s) in {len(out['groups'])} group(s), sizes {sizes}")


if __name__ == "__main__":
    main()
